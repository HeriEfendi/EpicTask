import { execSync } from 'node:child_process';
import { readFileSync, mkdirSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const tauriConfigPath = path.resolve(rootDir, 'frontend/src-tauri/tauri.conf.json');
const tauriConfig = JSON.parse(readFileSync(tauriConfigPath, 'utf8'));

const appName = tauriConfig.productName ? tauriConfig.productName.replace(/\s+/g, '.') : 'EpicTask';
const version = process.argv[2] || JSON.parse(readFileSync(path.resolve(rootDir, 'package.json'), 'utf8')).version;
const pkgName = 'epictask-desktop';
const arch = 'x86_64';
const pkgFileName = `${appName}-${version}-${arch}.pkg.tar.zst`;

console.log(`Building Arch Linux package: ${pkgFileName}...`);

const stageDir = path.resolve(`.pkg_stage_${Date.now()}`);
if (existsSync(stageDir)) rmSync(stageDir, { recursive: true, force: true });

mkdirSync(path.join(stageDir, 'usr/bin'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/applications'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/icons/hicolor/128x128/apps'), { recursive: true });
mkdirSync(path.join(stageDir, 'usr/share/icons/hicolor/32x32/apps'), { recursive: true });

// Copy binary from release build
const binarySrc = path.resolve(rootDir, 'frontend/src-tauri/target/release/epictask-desktop');
if (!existsSync(binarySrc)) {
  console.warn(`Warning: Binary not found at ${binarySrc}. Skipping Arch package.`);
  process.exit(0);
}

execSync(`cp "${binarySrc}" "${stageDir}/usr/bin/epictask-desktop"`);
execSync(`chmod 755 "${stageDir}/usr/bin/epictask-desktop"`);

// Create desktop file
const desktopContent = `[Desktop Entry]
Name=EpicTask
Comment=Modern Agile Project & Task Management Board
Exec=epictask-desktop
Icon=epictask-desktop
Terminal=false
Type=Application
Categories=Office;ProjectManagement;Development;
`;
writeFileSync(path.join(stageDir, 'usr/share/applications/epictask-desktop.desktop'), desktopContent);

// Copy icons
const icon128 = path.resolve(rootDir, 'frontend/src-tauri/icons/128x128.png');
const icon32 = path.resolve(rootDir, 'frontend/src-tauri/icons/32x32.png');
if (existsSync(icon128)) {
  execSync(`cp "${icon128}" "${stageDir}/usr/share/icons/hicolor/128x128/apps/epictask-desktop.png"`);
}
if (existsSync(icon32)) {
  execSync(`cp "${icon32}" "${stageDir}/usr/share/icons/hicolor/32x32/apps/epictask-desktop.png"`);
}

// Calculate binary size
const binarySize = readFileSync(path.join(stageDir, 'usr/bin/epictask-desktop')).length;

// Create .PKGINFO
const pkgInfoContent = `# Generated by create-arch-pkg
pkgname = ${pkgName}
pkgbase = ${pkgName}
pkgver = ${version}-1
pkgdesc = EpicTask Desktop - Modern Agile Project & Task Management
url = https://github.com/HeriEfendi/EpicTask
builddate = ${Math.floor(Date.now() / 1000)}
packager = Release Bot <noreply@github.com>
size = ${binarySize}
arch = ${arch}
license = MIT
depend = webkit2gtk-4.1
depend = gtk3
depend = cairo
depend = hicolor-icon-theme
depend = openssl
provides = ${pkgName}
conflicts = ${pkgName}
`;
writeFileSync(path.join(stageDir, '.PKGINFO'), pkgInfoContent);

// Create tar.zst
execSync(`tar -c --owner=root --group=root -C "${stageDir}" .PKGINFO usr | zstd -3 -o "${pkgFileName}"`, { stdio: 'inherit' });

// Cleanup
rmSync(stageDir, { recursive: true, force: true });

console.log(`Successfully created Arch Linux package: ${pkgFileName}`);
